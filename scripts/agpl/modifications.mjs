// Generate MODIFICATIONS.md: the ledger of every file this fork changed
// relative to the last synced upstream commit, with the date each was last
// changed here. This is the detailed companion to the dated notice in
// NOTICE.md (AGPL-3.0 section 5(a)).
//
// The "last synced upstream commit" is whatever upstream tip the fork has
// merged, recorded in UPSTREAM.md. Because it is the latest upstream the fork
// has, anything upstream did after it is not in HEAD, so a `git diff
// <sync>..HEAD` names exactly the files the fork changed and omits upstream's
// own later work. Dates come from the fork's own (non-merge) commits.
//
// Regenerate it in a release pull request (feat/release-<version>); it is
// never written by a bot commit to main.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import path from "node:path";

const COMMIT = /\b[0-9a-f]{40}\b/;

export function git(repoDir, args) {
  return execFileSync("git", ["-C", repoDir, ...args], {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
}

/**
 * The last synced upstream commit recorded in UPSTREAM.md: the first
 * 40-character SHA on the "Last synced upstream commit:" line.
 */
export function lastSyncedCommit(upstreamMarkdown) {
  for (const line of upstreamMarkdown.split("\n")) {
    if (/last synced upstream commit/i.test(line)) {
      const match = line.match(COMMIT);
      if (match) return match[0];
    }
  }
  throw new Error(
    "UPSTREAM.md has no 'Last synced upstream commit: <40-char sha>' line",
  );
}

const STATUS_LABEL = {
  A: "added",
  M: "modified",
  D: "deleted",
  R: "renamed",
  C: "copied",
  T: "type changed",
};

/** The newest fork (non-merge) commit date per path, since `sinceCommit`. */
function datesByPath(repoDir, sinceCommit, until) {
  const log = git(repoDir, [
    "log",
    "--no-merges",
    "--date=short",
    "--pretty=format:@commit %ad",
    "--name-only",
    `${sinceCommit}..${until}`,
  ]);
  const dates = new Map();
  let date = null;
  for (const raw of log.split("\n")) {
    if (raw.startsWith("@commit ")) {
      date = raw.slice("@commit ".length).trim();
    } else if (raw.trim() && date && !dates.has(raw)) {
      dates.set(raw, date);
    }
  }
  return dates;
}

/**
 * Every file whose current content differs from the last synced upstream
 * baseline, with its change type and the date it was last changed in the fork,
 * sorted by path.
 */
export function listModifications({ repoDir, since, until = "HEAD" }) {
  const nameStatus = git(repoDir, [
    "diff",
    "--name-status",
    "-M",
    since,
    until,
  ]);
  const dates = datesByPath(repoDir, since, until);
  const entries = [];
  for (const raw of nameStatus.split("\n")) {
    if (!raw.trim()) continue;
    const parts = raw.split("\t");
    const code = parts[0][0];
    // Renames and copies carry the destination path last.
    const file = parts[parts.length - 1];
    entries.push({
      path: file,
      status: STATUS_LABEL[code] ?? "changed",
      date: dates.get(file) ?? null,
    });
  }
  entries.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  return entries;
}

/** Render the ledger as Markdown. */
export function renderModifications(entries, { project, since, generatedAt }) {
  const header = [
    "# Modifications",
    "",
    "<!-- Generated by scripts/agpl/modifications.mjs. Do not edit by hand. -->",
    "",
    `This fork is a modified version of ${project}. Under section 5(a) of the`,
    "GNU Affero General Public License v3.0, this is the dated record of every",
    "file changed relative to the last synced upstream commit",
    `\`${since}\`. The prominent notice is in [NOTICE.md](NOTICE.md); the full`,
    "history is in the public git log.",
    "",
    `Generated ${generatedAt} against \`${since}\`. ${entries.length} file` +
      `${entries.length === 1 ? "" : "s"} changed.`,
    "",
    "| File | Change | Last changed |",
    "| --- | --- | --- |",
  ];
  const rows = entries.map(
    (entry) => `| \`${entry.path}\` | ${entry.status} | ${entry.date ?? "—"} |`,
  );
  return `${[...header, ...rows].join("\n")}\n`;
}

function main(argv) {
  const repoDir = argValue(argv, "--repo") ?? process.cwd();
  const since =
    argValue(argv, "--since") ??
    lastSyncedCommit(readFileSync(path.join(repoDir, "UPSTREAM.md"), "utf8"));
  const out = argValue(argv, "--out") ?? path.join(repoDir, "MODIFICATIONS.md");
  const project = argValue(argv, "--project") ?? "the upstream project";
  const entries = listModifications({ repoDir, since });
  const generatedAt = new Date().toISOString().slice(0, 10);
  const markdown = renderModifications(entries, { project, since, generatedAt });
  if (argv.includes("--check")) {
    const current = readFileSync(out, "utf8");
    if (current !== markdown) {
      console.error(
        `${out} is out of date. Regenerate it with: node scripts/agpl/modifications.mjs`,
      );
      process.exit(1);
    }
    return;
  }
  writeFileSync(out, markdown);
  console.log(`Wrote ${out} (${entries.length} files).`);
}

function argValue(argv, name) {
  const index = argv.indexOf(name);
  return index >= 0 && index + 1 < argv.length ? argv[index + 1] : undefined;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2));
}

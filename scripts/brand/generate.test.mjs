// Tests for scripts/brand/generate.mjs: the committed brand modules match
// brand.json (the drift check), and an invalid brand config is refused with
// the offending field named.
//
// Run: node --test scripts/brand/generate.test.mjs

import { deepStrictEqual, match, ok, strictEqual, throws } from "node:assert";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { after, describe, test } from "node:test";
import { fileURLToPath } from "node:url";
import {
    BRAND_FILE,
    BrandConfigError,
    OUTPUT_FILES,
    REPO_ROOT,
    SCHEMA_FILE,
    brandProblems,
    contrastRatio,
    generate,
    renderModule,
    resolveBrand,
} from "./generate.mjs";

const GENERATOR = join(dirname(fileURLToPath(import.meta.url)), "generate.mjs");
const read = (file) => readFileSync(join(REPO_ROOT, file), "utf8");
const schema = JSON.parse(read(SCHEMA_FILE));
const config = JSON.parse(read(BRAND_FILE));
/** A fresh, mutable copy of the committed brand.json. */
const fresh = () => structuredClone(config);

const temporary = [];
after(() => {
    for (const dir of temporary) rmSync(dir, { recursive: true, force: true });
});

describe("generated modules", () => {
    test("both committed modules equal the generator's output for brand.json", () => {
        const expected = renderModule(config, schema);
        for (const file of OUTPUT_FILES) {
            strictEqual(read(file), expected, `${file} is out of date: run node scripts/brand/generate.mjs`);
        }
        deepStrictEqual(generate({ check: true }), []);
    });

    test("the committed brand.json is valid", () => {
        deepStrictEqual(brandProblems(config, schema), []);
    });

    test("every module starts with the licence line and names its source", () => {
        const module = renderModule(config, schema);
        strictEqual(module.split("\n")[0], "// SPDX-License-Identifier: AGPL-3.0-only");
        match(module, /Generated by scripts\/brand\/generate\.mjs from packages\/brand\/brand\.json/);
        match(module, /^export const brand: Brand = \{$/m);
    });
});

describe("schema validation names the field", () => {
    for (const field of ["productName", "supportEmail", "securityEmail", "sourceRepositoryUrl", "legalDocuments", "palette"]) {
        test(`missing ${field}`, () => {
            const broken = fresh();
            delete broken[field];
            deepStrictEqual(brandProblems(broken, schema), [`${field} is required`]);
            throws(
                () => renderModule(broken, schema),
                (error) => error instanceof BrandConfigError && error.message.includes(`${field} is required`),
            );
        });
    }

    test("a legal document without a version", () => {
        const broken = fresh();
        delete broken.legalDocuments.dpa.version;
        deepStrictEqual(brandProblems(broken, schema), ["legalDocuments.dpa.version is required"]);
    });

    test("a missing legal document", () => {
        const broken = fresh();
        delete broken.legalDocuments.aiTransparency;
        deepStrictEqual(brandProblems(broken, schema), ["legalDocuments.aiTransparency is required"]);
    });

    test("values of the wrong shape", () => {
        const broken = fresh();
        broken.supportEmail = "support at example";
        broken.appUrl = "http://app.example.com";
        broken.legalDocuments.terms.status = "final";
        broken.legalDocuments.privacy.version = "";
        broken.palette.primary = "blue";
        broken.displayFace = "comic-sans";
        broken.assets.ogImage = "https://cdn.example.com/og.png";
        broken.productName = "A".repeat(41);
        broken.unexpected = true;
        const problems = brandProblems(broken, schema);
        for (const field of [
            "supportEmail does not match the expected format (a mailbox address)",
            "appUrl does not match the expected format (an absolute https address)",
            "legalDocuments.terms.status must be one of",
            "legalDocuments.privacy.version does not match",
            "palette.primary does not match",
            "displayFace must be one of",
            "assets.ogImage does not match",
            "productName must be at most 40 characters",
            "unexpected is not a known field",
        ]) {
            ok(problems.some((problem) => problem.startsWith(field)), `expected "${field}…" in:\n${problems.join("\n")}`);
        }
    });

    test("markup and padding in display text", () => {
        for (const productName of ["<b>Name</b>", " Name", "Name ", "Line\nbreak"]) {
            const broken = { ...fresh(), productName };
            ok(
                brandProblems(broken, schema).some((p) => p.startsWith("productName does not match")),
                JSON.stringify(productName),
            );
        }
    });

    test("an unreadable primary colour pairing", () => {
        const broken = fresh();
        broken.palette = { primary: "#777777", onPrimary: "#FFFFFF" };
        const problems = brandProblems(broken, schema);
        strictEqual(problems.length, 1);
        match(problems[0], /^palette\.onPrimary has a contrast of 4\.48:1 on palette\.primary; it must be at least 4\.5:1$/);
        strictEqual(Number(contrastRatio("#000000", "#FFFFFF").toFixed(1)), 21);
    });
});

describe("resolved values", () => {
    test("the assistant and the Word author default to the product name", () => {
        const brand = resolveBrand({ ...fresh(), productName: "Acme" }, schema);
        strictEqual(brand.assistantName, "Acme Assistant");
        strictEqual(brand.docxAuthorLabel, "Acme Assistant");
    });

    test("explicit names win, and the Word author follows the assistant", () => {
        const brand = resolveBrand({ ...fresh(), assistantName: "Drafting Aid" }, schema);
        strictEqual(brand.docxAuthorLabel, "Drafting Aid");
        strictEqual(resolveBrand({ ...fresh(), docxAuthorLabel: "Reviewer" }, schema).docxAuthorLabel, "Reviewer");
    });

    test("the derived names fit the schema even for the longest product name", () => {
        const longest = { ...fresh(), productName: "N".repeat(40) };
        deepStrictEqual(brandProblems(longest, schema), []);
        strictEqual(resolveBrand(longest, schema).assistantName.length, 50);
    });

    test("editor-only keys are dropped and keys follow the schema's order", () => {
        const shuffled = Object.fromEntries(Object.entries(fresh()).reverse());
        const brand = resolveBrand(shuffled, schema);
        ok(!("$schema" in brand) && !("$comment" in brand));
        deepStrictEqual(
            Object.keys(brand),
            Object.keys(schema.properties).filter((key) => !key.startsWith("$")),
        );
        strictEqual(renderModule(shuffled, schema), renderModule(config, schema));
    });
});

describe("command line", () => {
    function checkout() {
        const root = mkdtempSync(join(tmpdir(), "brand-generate-"));
        temporary.push(root);
        mkdirSync(join(root, "packages", "brand"), { recursive: true });
        for (const file of [BRAND_FILE, SCHEMA_FILE]) writeFileSync(join(root, file), read(file));
        for (const file of OUTPUT_FILES) mkdirSync(dirname(join(root, file)), { recursive: true });
        return root;
    }
    const run = (...args) => spawnSync(process.execPath, [GENERATOR, ...args], { encoding: "utf8" });

    test("writes both modules, then --check passes", () => {
        const root = checkout();
        const written = run("--root", root);
        strictEqual(written.status, 0, written.stderr);
        for (const file of OUTPUT_FILES) strictEqual(readFileSync(join(root, file), "utf8"), read(file));
        strictEqual(run("--root", root, "--check").status, 0);
    });

    test("--check fails and names the stale module when brand.json changes", () => {
        const root = checkout();
        strictEqual(run("--root", root).status, 0);
        const edited = { ...fresh(), productName: "Renamed" };
        writeFileSync(join(root, BRAND_FILE), JSON.stringify(edited, null, 2));
        const checked = run("--root", root, "--check");
        strictEqual(checked.status, 1);
        for (const file of OUTPUT_FILES) match(checked.stderr, new RegExp(file.replaceAll(".", "\\.")));
        // Nothing was rewritten by --check.
        for (const file of OUTPUT_FILES) strictEqual(readFileSync(join(root, file), "utf8"), read(file));
    });

    test("an invalid brand.json fails with the field named and writes nothing", () => {
        const root = checkout();
        const broken = fresh();
        delete broken.legalDocuments.cookies.version;
        writeFileSync(join(root, BRAND_FILE), JSON.stringify(broken));
        const result = run("--root", root);
        strictEqual(result.status, 1);
        match(result.stderr, /legalDocuments\.cookies\.version is required/);
        for (const file of OUTPUT_FILES) {
            throws(() => readFileSync(join(root, file)), { code: "ENOENT" });
        }
    });
});

describe("Word add-in alias", () => {
    test("@mike/brand resolves to the generated web module in tsc and webpack", () => {
        const target = resolve(REPO_ROOT, OUTPUT_FILES[0]);
        const tsconfig = JSON.parse(read("word-addin/tsconfig.json"));
        deepStrictEqual(
            (tsconfig.compilerOptions.paths["@mike/brand"] ?? []).map((p) => resolve(REPO_ROOT, "word-addin", p)),
            [target],
        );
        // webpack.config.js needs the add-in's dependencies to load, so read the
        // alias line and resolve it the way its frontendShared() helper does.
        const webpack = read("word-addin/webpack.config.js");
        match(webpack, /const frontendShared = \(\.\.\.segments\) =>\s*path\.resolve\(__dirname, "\.\.", "frontend", "src", "shared", \.\.\.segments\)/);
        const alias = /"@mike\/brand":\s*frontendShared\(([^)]*)\)/.exec(webpack);
        ok(alias, "webpack.config.js has no @mike/brand alias");
        const segments = JSON.parse(`[${alias[1]}]`);
        strictEqual(resolve(REPO_ROOT, "frontend", "src", "shared", ...segments), target);
    });
});
